const GENERATED_AT = '2026-08-02T12:00:00.000Z';

function packetInput(overrides: Partial<Parameters<typeof buildApplicationPacket>[0]> = {}) {
  const draft = markdownToDraft('# Need statement\n\nText.', {
    title: 'Draft',
    provenanceNote: 'Generated by GrantSpotter on 2026-08-02.',
  });
  return {
    program: PROGRAM,
    funder: makeFunder(),
    draft,
    budgetLines: LINES,
    generatedAtISO: GENERATED_AT,
    ...overrides,
  };
}

/** Every packet entry as text — the nested DOCX expanded, so nothing hides inside a second ZIP. */
function packetText(zip: Uint8Array): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, data] of Object.entries(unzipSync(zip))) {
    if (name.endsWith('.docx')) {
      for (const [inner, innerData] of Object.entries(unzipSync(data))) {
        if (inner.endsWith('.xml') || inner.endsWith('.rels')) out[`${name}!${inner}`] = strFromU8(innerData);
      }
      continue;
    }
    out[name] = strFromU8(data);
  }
  return out;
}

