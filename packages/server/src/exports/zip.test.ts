describe('budgetWorksheetCsv', () => {
  it('computes line totals and a grand total', () => {
    const csv = budgetWorksheetCsv(LINES, PROGRAM);
    expect(csv).toContain('IC-7610 transceiver');
    expect(csv).toContain('2899');
    expect(csv).toContain('291'); // 2 x 145.50
    expect(csv).toContain('TOTAL');
    expect(csv).toContain('3190');
  });

  it('adds an indirect-cost cap row when the funder caps indirect costs', () => {
    const csv = budgetWorksheetCsv(LINES, PROGRAM);
    expect(csv).toContain('Indirect cost cap (20%)');
    expect(csv).toContain('638'); // 20% of 3190
  });

  it('omits the indirect row when the funder sets no cap', () => {
    expect(budgetWorksheetCsv(LINES, makeProgram())).not.toContain('Indirect cost cap');
  });

  /**
   * `costShareRequired` is UNSTATED on 148 of the 150 publishable programmes and `false` on ZERO.
   * A worksheet that answered the matching-funds question with silence — or worse, with "no match
   * required" — would put a claim in the applicant's budget that no funder has made.
   */
  it('says the funder has not addressed cost share, and never that no match is required', () => {
    const csv = budgetWorksheetCsv(LINES, makeProgram());
    expect(csv).toContain('Cost share');
    expect(csv).toMatch(/has not said|not stated|unstated/i);
    expect(csv).not.toMatch(/no match(ing)? (is )?(funds? )?required/i);
    expect(csv).not.toMatch(/cost share is not required/i);
  });

  it('reports a stated obligation as stated, in both directions', () => {
    expect(budgetWorksheetCsv(LINES, PROGRAM)).toMatch(/is not required/i);
    const required = makeProgram({ obligations: { costShareRequired: true } });
    expect(budgetWorksheetCsv(LINES, required)).toMatch(/is required/i);
  });
});

