const LINES: BudgetLine[] = [
  {
    item: 'IC-7610 transceiver',
    category: 'Equipment',
    quantity: 1,
    unitCost: 2899,
    justification: 'Replaces a 1998 radio',
    quoteSource: 'https://www.example.org/quote-2026-07',
  },
  {
    item: 'Coaxial cable, 200 ft',
    category: 'Materials',
    quantity: 2,
    unitCost: 145.5,
    justification: 'Feedline replacement',
    quoteSource: 'https://www.example.org/quote-2026-07',
  },
];

const PROGRAM = makeProgram({
  fundingRestrictions: ['No emergency-communications equipment', 'No ongoing operating expenses'],
  obligations: {
    costShareRequired: false,
    coFunderPreference: true,
    indirectCostCapPct: 20,
    licenseObligation: 'All output must be open-source or open-access (GPL, MIT, BSD, CERN-OHL or CC).',
  },
  constraints: [
    {
      id: 'c-hard-entity',
      hard: true,
      fallbackRank: 0,
      rawText: 'Applicant must be a US 501(c)(3), government body, school or university.',
      spec: { axis: 'other', note: 'US 501(c)(3), government, school or university' },
    },
    {
      id: 'c-soft-gpa',
      hard: false,
      fallbackRank: 0,
      rawText: 'Preference is given to applicants with a GPA over 3.5.',
      spec: { axis: 'gpa', min: 3.5 },
    },
  ],
});

const GENERATED_AT = '2026-08-02T12:00:00.000Z';

function packetInput(overrides: Partial<Parameters<typeof buildApplicationPacket>[0]> = {}) {
  const draft = markdownToDraft('# Need statement\n\nText.', {
    title: 'Draft',
    provenanceNote: 'Generated by GrantSpotter on 2026-08-02.',
  });
  return {
    program: PROGRAM,
    funder: makeFunder(),
    draft,
    budgetLines: LINES,
    generatedAtISO: GENERATED_AT,
    ...overrides,
  };
}

/** Every packet entry as text — the nested DOCX expanded, so nothing hides inside a second ZIP. */
function packetText(zip: Uint8Array): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, data] of Object.entries(unzipSync(zip))) {
    if (name.endsWith('.docx')) {
      for (const [inner, innerData] of Object.entries(unzipSync(data))) {
        if (inner.endsWith('.xml') || inner.endsWith('.rels')) out[`${name}!${inner}`] = strFromU8(innerData);
      }
      continue;
    }
    out[name] = strFromU8(data);
  }
  return out;
}

