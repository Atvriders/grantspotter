describe('buildApplicationPacket', () => {
  it('contains exactly the six packet entries', async () => {
    const entries = unzipSync(await buildApplicationPacket(packetInput()));
    expect(Object.keys(entries).sort()).toEqual([
      'README.txt',
      'budget-worksheet.csv',
      'draft.docx',
      'draft.md',
      'requirements-checklist.md',
      'source-links.md',
    ]);
    expect(strFromU8(entries['README.txt'] as Uint8Array)).toContain('ARDC Grants Program');
    expect(strFromU8(entries['draft.md'] as Uint8Array)).toContain('# Need statement');
    expect((entries['draft.docx'] as Uint8Array).subarray(0, 2)).toEqual(new Uint8Array([0x50, 0x4b]));
  });

  it('ships a DOCX the packet reader can open and read the draft out of', async () => {
    const entries = unzipSync(await buildApplicationPacket(packetInput()));
    const inner = unzipSync(entries['draft.docx'] as Uint8Array);
    expect(Object.keys(inner)).toContain('word/document.xml');
    expect(strFromU8(inner['word/document.xml'] as Uint8Array)).toContain('Need statement');
  });

  it('is byte-identical across two runs with the same input', async () => {
    const input = packetInput();
    const a = await buildApplicationPacket(input);
    const b = await buildApplicationPacket(input);
    expect(Buffer.from(a).equals(Buffer.from(b))).toBe(true);
  });

  it('names its own contents in the README, so no entry is a mystery', async () => {
    const readme = packetText(await buildApplicationPacket(packetInput()))['README.txt'] ?? '';
    for (const entry of [
      'draft.md',
      'draft.docx',
      'budget-worksheet.csv',
      'requirements-checklist.md',
      'source-links.md',
    ]) {
      expect(readme).toContain(entry);
    }
  });

  /**
   * `farweb.org` must not reach a funder's inbox as an address, in ANY entry — not in the source
   * list, not in a verbatim quote of the funder's own page, not in a budget quote URL a user
   * typed, and not compressed inside the DOCX where a byte search of the outer ZIP would miss it.
   */
  it('carries no blocklisted host in any entry, including inside the DOCX', async () => {
    const hijacked = makeProgram({
      applyUrl: 'https://www.farweb.org/scholarships',
      applyContact: 'See farweb.org for the packet.',
      rawOtherText: 'Applicants should apply at the FAR website, http://www.farweb.org/apply.html.',
      trust: { ...PROGRAM.trust, sourceUrl: 'https://www.qcwa.org/scholarships.htm' },
    });
    const zip = await buildApplicationPacket(
      packetInput({
        program: hijacked,
        funder: makeFunder({ homepage: 'https://farweb.org/' }),
        draft: markdownToDraft('# Need\n\nWe were told to apply at https://www.farweb.org/apply.html.', {
          title: 'Draft',
          provenanceNote: 'note',
        }),
        budgetLines: [{ ...(LINES[0] as BudgetLine), quoteSource: 'http://farweb.org/quote' }],
      }),
    );
    const text = packetText(zip);
    expect(Object.keys(text).length).toBeGreaterThan(6);
    for (const [name, body] of Object.entries(text)) {
      expect(body, `${name} carries the hijacked host`).not.toMatch(/farweb/i);
      expect(body, `${name} carries the takeover target`).not.toMatch(/batualam/i);
    }
    expect(text['source-links.md']).toContain('link withheld');
  });

  it('tells the reader in the README that GrantSpotter vouches for nothing in the packet', async () => {
    const readme = packetText(await buildApplicationPacket(packetInput()))['README.txt'] ?? '';
    expect(readme).toContain('did not write your application');
    expect(readme).toContain('Verify each one before you submit.');
  });
});

