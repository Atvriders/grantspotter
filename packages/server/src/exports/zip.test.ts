describe('requirementsChecklistMarkdown', () => {
  const md = requirementsChecklistMarkdown(PROGRAM, makeFunder());

  it('separates hard requirements from preferences and never calls a preference a requirement', () => {
    const hardIdx = md.indexOf('## Requirements (must be true)');
    const softIdx = md.indexOf('## Preferences (these rank you, they never exclude you)');
    expect(hardIdx).toBeGreaterThan(-1);
    expect(softIdx).toBeGreaterThan(hardIdx);
    expect(md.slice(hardIdx, softIdx)).toContain('US 501(c)(3)');
    expect(md.slice(softIdx)).toContain('GPA over 3.5');
  });

  it('lists funding restrictions and obligations as checkboxes', () => {
    expect(md).toContain('- [ ] No emergency-communications equipment');
    expect(md).toContain('- [ ] No ongoing operating expenses');
    expect(md).toContain('open-source or open-access');
    expect(md).toContain('Indirect costs capped at 20%');
    expect(md).toContain('prefers not to be the sole funder');
  });

  it('states how to apply and the last-verified provenance', () => {
    expect(md).toContain('external_spa_portal');
    expect(md).toContain('https://www.ardc.net/apply/');
    expect(md).toContain('last verified 2026-08-02');
  });

  /**
   * Only 4 of the 243 cycles this corpus carries are dates a funder published; the other 239 are
   * computed from a recurrence rule. A checklist that printed one as "the deadline" is the exact
   * failure this project spent the most effort removing, so it prints the funder's own deadline
   * words and NO computed date at all, and says which is which.
   */
  it('quotes the funder’s own deadline words and no projected date', () => {
    expect(md).toContain('February 1, April 1, July 1, September 1.');
    expect(md).toMatch(/projects most cycle dates from a recurrence rule/i);
    // The only ISO date the file may carry is the provenance stamp saying when we last read the
    // page. Any other would be a date GrantSpotter computed, wearing the funder's authority.
    const withoutProvenance = md
      .split('\n')
      .filter((line) => !line.includes('last verified'))
      .join('\n');
    expect(withoutProvenance).not.toMatch(/\b20\d{2}-\d{2}-\d{2}\b/);
  });

  it('reports an unstated obligation as unstated rather than omitting the question', () => {
    const bare = requirementsChecklistMarkdown(makeProgram(), makeFunder());
    expect(bare).toMatch(/Cost share[^\n]*has not said/i);
    expect(bare).not.toMatch(/cost share is not required/i);
  });

  it('marks an inherited deadline as somebody else’s, because 111 ARRL entries share one', () => {
    const inherited = makeProgram({
      deadline: { kind: 'inherited', source: { kind: 'inherited', fromProgramId: 'arrl-foundation' }, note: 'One application, one deadline.' },
    });
    expect(requirementsChecklistMarkdown(inherited, makeFunder())).toContain('arrl-foundation');
  });
});

