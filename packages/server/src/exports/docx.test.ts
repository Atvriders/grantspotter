// ---------------------------------------------------------------------------
// Readers that open the archive and read the parts, never the byte length.
// ---------------------------------------------------------------------------

function parts(buf: Buffer | Uint8Array): Record<string, Uint8Array> {
  return unzipSync(new Uint8Array(buf));
}

function documentXml(buf: Buffer | Uint8Array): string {
  const part = parts(buf)['word/document.xml'];
  expect(part, 'word/document.xml must exist in the archive').toBeDefined();
  return strFromU8(part as Uint8Array);
}

function decodeXml(value: string): string {
  return value
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
}

/** Every `<w:t>` run in document order — what a reader of the Word file actually sees. */
function runs(xml: string): string[] {
  return [...xml.matchAll(/<w:t(?: [^>]*)?>([\s\S]*?)<\/w:t>/g)].map((m) => decodeXml(m[1] as string));
}

/** The visible text, one entry per `<w:p>`, runs concatenated. This is the readable document. */
function paragraphs(xml: string): string[] {
  return [...xml.matchAll(/<w:p(?: [^>]*)?>([\s\S]*?)<\/w:p>/g)].map((m) => runs(m[1] as string).join(''));
}

/** The `<w:r>` elements of one paragraph, so a test can ask how a single run is styled. */
function runElements(xml: string, paragraphIndex: number): string[] {
  const paragraph = [...xml.matchAll(/<w:p(?: [^>]*)?>([\s\S]*?)<\/w:p>/g)][paragraphIndex]?.[1] ?? '';
  return [...paragraph.matchAll(/<w:r>[\s\S]*?<\/w:r>/g)].map((m) => m[0]);
}

