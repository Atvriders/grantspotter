describe('draftToDocx', () => {
  it('produces a ZIP container holding word/document.xml', async () => {
    const buf = await draftToDocx(markdownToDraft(MD, META));
    expect(buf.subarray(0, 2).toString('latin1')).toBe('PK');
    expect(Object.keys(parts(buf))).toContain('word/document.xml');
  });

  it('is still a readable OPC package after the timestamps are normalised', async () => {
    const buf = await draftToDocx(markdownToDraft(MD, META), { generatedAtISO: '2026-08-02T12:00:00.000Z' });
    const entries = parts(buf);
    for (const required of ['[Content_Types].xml', '_rels/.rels', 'word/document.xml', 'word/styles.xml']) {
      expect(Object.keys(entries)).toContain(required);
    }
    expect(strFromU8(entries['[Content_Types].xml'] as Uint8Array)).toContain(
      'wordprocessingml.document.main+xml',
    );
    expect(strFromU8(entries['docProps/core.xml'] as Uint8Array)).toContain('2026-08-02T12:00:00.000Z');
  });

  it('carries the title, headings, bullet text, TODO marker, fact checklist and disclosure', async () => {
    const xml = documentXml(await draftToDocx(markdownToDraft(MD, META)));
    expect(xml).toContain('ARDC Grants Program');
    expect(xml).toContain('Need statement');
    expect(xml).toContain('Train 12 new operators');
    expect(xml).toContain('how many members hold a General class licence');
    expect(xml).toContain('Fact checklist');
    expect(xml).toContain('large language model');
    expect(xml).toContain('Generated by GrantSpotter on 2026-08-02');
  });

  it('renders TODO text with a highlight so it cannot be shipped unnoticed', async () => {
    const xml = documentXml(await draftToDocx(markdownToDraft(MD, META)));
    expect(xml).toMatch(/<w:highlight w:val="yellow"\/>/);
  });

  /**
   * THE GAP HAS TO SURVIVE INTO WORD AND STILL LOOK LIKE A GAP. `stripTodoMarkers` exists and is
   * an ANALYSIS helper; an applicant-facing renderer that used it would delete the brackets and
   * leave the hint text — `the club's callsign, e.g. W8UM` — sitting in a sentence as though the
   * applicant had written it.
   */
  it('keeps the whole marker, brackets and example included, in the extracted document text', async () => {
    const marker = "[TODO: club.callsign — the club's callsign, e.g. W8UM]";
    const xml = documentXml(await draftToDocx(markdownToDraft(`# S\n\n${marker}`, META)));
    expect(paragraphs(xml)).toContain(marker);
    expect(runs(xml)).toContain(marker);
  });

  it('gives an inline gap its own loud run without disturbing the sentence around it', async () => {
    const sentence = 'The station operates from [TODO: club.venue — where the station lives] on campus.';
    const xml = documentXml(await draftToDocx(markdownToDraft(`# S\n\n${sentence}`, META)));
    const index = paragraphs(xml).indexOf(sentence);
    expect(index, 'the sentence must survive intact').toBeGreaterThan(-1);
    const [before, gap, after] = runElements(xml, index);
    expect(before).toContain('The station operates from ');
    expect(before).not.toContain('<w:highlight');
    expect(gap).toContain('[TODO: club.venue — where the station lives]');
    expect(gap).toContain('<w:highlight w:val="yellow"/>');
    expect(gap).toContain('<w:b/>');
    expect(gap).toContain('<w:color w:val="B00020"/>');
    expect(after).toContain(' on campus.');
    expect(after).not.toContain('<w:highlight');
  });

  it('makes a gap inside a bullet just as loud as one in a paragraph', async () => {
    const xml = documentXml(
      await draftToDocx(markdownToDraft('# S\n\n- Train [TODO: project.traineeCount — how many] operators', META)),
    );
    const index = paragraphs(xml).indexOf('Train [TODO: project.traineeCount — how many] operators');
    expect(index).toBeGreaterThan(-1);
    expect(runElements(xml, index).some((r) => r.includes('<w:highlight w:val="yellow"/>'))).toBe(true);
  });

  it('prints the checklist scope note, so the packet never implies everything was verified', async () => {
    const xml = documentXml(await draftToDocx(markdownToDraft(MD, META)));
    expect(paragraphs(xml).join('\n')).toContain(CHECKLIST_SCOPE_NOTE);
  });

  it('renders a table as a Word table rather than a wall of pipe characters', async () => {
    const xml = documentXml(
      await draftToDocx(markdownToDraft('# S\n\n| Phase | Who |\n|---|---|\n| 1 | Dana |', META)),
    );
    expect(xml).toContain('<w:tbl>');
    expect(runs(xml)).toEqual(expect.arrayContaining(['Phase', 'Who', '1', 'Dana']));
    expect(runs(xml).join('')).not.toContain('|---|');
  });

  it('is byte-identical across two runs when the generation instant is stated', async () => {
    const draft = markdownToDraft(MD, META);
    const opts = { generatedAtISO: '2026-08-02T12:00:00.000Z' };
    const a = await draftToDocx(draft, opts);
    const b = await draftToDocx(draft, opts);
    expect(a.equals(b)).toBe(true);
  });
});

