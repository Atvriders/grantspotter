const APPLICATIONS_DDL = `
  CREATE TABLE applications (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    program_id TEXT,
    title TEXT NOT NULL,
    body_markdown TEXT NOT NULL DEFAULT '',
    answers_json TEXT NOT NULL DEFAULT '{}',
    fact_confirmations_json TEXT NOT NULL DEFAULT '{}',
    include_disclosure INTEGER NOT NULL DEFAULT 1,
    facts_confirmed_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
  );
  CREATE TABLE profiles (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    data TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (user_id, kind)
  );`;

const NOW = '2026-08-02T12:00:00.000Z';
const clock = (): string => NOW;

function draftWith(body: string): { db: Database.Database; id: string } {
  const db = new Database(':memory:');
  db.exec(APPLICATIONS_DDL);
  const app = createApplication(db, { userId: 'user-1', title: 'Draft' }, clock);
  updateApplication(db, app.id, 'user-1', { bodyMarkdown: body }, clock);
  return { db, id: app.id };
}

function confirmEverything(db: Database.Database, id: string, body: string): void {
  const incoming = Object.fromEntries(
    extractFactAssertions(body).map((f) => [f.id, { confirmed: true, note: '' }]),
  );
  setFactConfirmations(db, id, 'user-1', resolveConfirmations(body, incoming).resolved, clock);
}

/** What the export route does, in the route's order. A renderer never runs before the gate. */
async function exportDraft(db: Database.Database, id: string, body: string): Promise<Buffer> {
  assertExportReady(db, id, 'user-1');
  return draftToDocx(markdownToDraft(body, META));
}

describe('the export gate refuses a draft the applicant has not signed off', () => {
  it('throws 409 for an unconfirmed factual assertion, and renders nothing', async () => {
    const body = '# Budget\n\nOne transceiver at $2,899.';
    const { db, id } = draftWith(body);
    await expect(exportDraft(db, id, body)).rejects.toThrow(AppError);
    await expect(exportDraft(db, id, body)).rejects.toMatchObject({ code: 'conflict', status: 409 });
  });

  it('throws 409 while a [TODO: …] marker is still open', async () => {
    const body = "# Need statement\n\nOur club needs [TODO: club.callsign — the club's callsign, e.g. W8UM].";
    const { db, id } = draftWith(body);
    await expect(exportDraft(db, id, body)).rejects.toMatchObject({ code: 'conflict', status: 409 });
  });

  it('renders once every assertion is confirmed and no gap is left', async () => {
    const body = '# Budget\n\nOne transceiver at $2,899.';
    const { db, id } = draftWith(body);
    confirmEverything(db, id, body);
    const buf = await exportDraft(db, id, body);
    expect(buf.subarray(0, 2).toString('latin1')).toBe('PK');
    expect(documentXml(buf)).toContain('$2,899');
  });

  /**
   * A confirmation is FINGERPRINTED, so ticking `$1,450` does not silently carry over to `$9,999`
   * typed at the same character width — the id is a position, and a position alone would.
   */
  it('re-blocks the export when a confirmed figure is edited to another of the same width', async () => {
    const before = '# Budget\n\nOne transceiver at $1,450.';
    const after = '# Budget\n\nOne transceiver at $9,999.';
    const { db, id } = draftWith(before);
    confirmEverything(db, id, before);
    await expect(exportDraft(db, id, before)).resolves.toBeInstanceOf(Buffer);

    updateApplication(db, id, 'user-1', { bodyMarkdown: after }, clock);
    await expect(exportDraft(db, id, after)).rejects.toMatchObject({ code: 'conflict', status: 409 });
  });

  it('answers 404, never 409, for a draft belonging to somebody else', () => {
    const { db, id } = draftWith('# S\n\nNo facts here at all.');
    expect(() => assertExportReady(db, id, 'user-2')).toThrow(AppError);
    try {
      assertExportReady(db, id, 'user-2');
    } catch (error) {
      expect((error as AppError).code).toBe('not_found');
    }
  });
});
