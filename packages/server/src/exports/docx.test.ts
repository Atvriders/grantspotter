describe('markdownToDraft', () => {
  it('splits on the shallowest heading level and keeps paragraph order', () => {
    const draft = markdownToDraft(MD, META);
    expect(draft.sections.map((s) => s.heading)).toEqual(['Need statement', 'Budget']);
    expect(draft.sections[0]?.blocks[0]).toEqual({
      kind: 'p',
      text: 'The W8UM club station has run on a 1998 transceiver since 2019.',
    });
  });

  it('groups consecutive dash bullets into one bullet block', () => {
    const draft = markdownToDraft(MD, META);
    expect(draft.sections[0]?.blocks[1]).toEqual({
      kind: 'bullet',
      items: ['Replace the transceiver', 'Train 12 new operators'],
    });
  });

  it('classifies a [TODO: ...] line as a todo block, not a paragraph', () => {
    const draft = markdownToDraft(MD, META);
    expect(draft.sections[0]?.blocks[2]).toEqual({
      kind: 'todo',
      text: '[TODO: how many members hold a General class licence?]',
    });
  });

  it('puts content before the first heading into an untitled leading section', () => {
    const draft = markdownToDraft('Intro line.\n\n# Body\n\ntext', META);
    expect(draft.sections[0]?.heading).toBe('');
    expect(draft.sections[0]?.blocks[0]).toEqual({ kind: 'p', text: 'Intro line.' });
  });

  /**
   * EVERY TEMPLATE THIS PRODUCT SHIPS USES `##` FOR ITS HEADINGS — 120 of them under `content/`,
   * and not one `#`. A splitter that only knows `#` flattens a filled template into ONE untitled
   * section whose section titles have become body paragraphs, which is the whole document.
   */
  it('splits a level-2 document into sections too, because the shipped templates are all level 2', () => {
    const draft = markdownToDraft('## What this section has to do\n\nShow the work.\n\n## Skeleton\n\nRows.', META);
    expect(draft.sections.map((s) => s.heading)).toEqual(['What this section has to do', 'Skeleton']);
  });

  it('keeps a deeper heading as a heading block rather than dissolving it into prose', () => {
    const draft = markdownToDraft('# Top\n\n## Inner\n\nbody', META);
    expect(draft.sections.map((s) => s.heading)).toEqual(['Top']);
    expect(draft.sections[0]?.blocks[0]).toEqual({ kind: 'heading', level: 2, text: 'Inner' });
  });

  it('keeps an ordered list as an ordered list instead of one run-on paragraph', () => {
    const draft = markdownToDraft('# S\n\n1. Order the radio\n2. Install the feedline', META);
    expect(draft.sections[0]?.blocks[0]).toEqual({
      kind: 'ordered',
      items: ['Order the radio', 'Install the feedline'],
    });
  });

  it('keeps a blockquote separate, because template guidance is not the applicant’s own prose', () => {
    const draft = markdownToDraft('# S\n\n> Do not write: "materials will be procured".', META);
    expect(draft.sections[0]?.blocks[0]).toEqual({
      kind: 'quote',
      lines: ['Do not write: "materials will be procured".'],
    });
  });

  it('parses a pipe table into rows and drops the alignment rule', () => {
    const draft = markdownToDraft('# S\n\n| Phase | Who |\n|---|---|\n| 1 | Dana |', META);
    expect(draft.sections[0]?.blocks[0]).toEqual({
      kind: 'table',
      rows: [
        ['Phase', 'Who'],
        ['1', 'Dana'],
      ],
    });
  });

  /**
   * SPEC §10.1. `fillTemplate` substitutes a slot IN PLACE, so the overwhelmingly common gap is
   * mid-sentence, not on a line of its own. The line-only classifier the brief specified read an
   * inline gap as ordinary prose, and ordinary prose is rendered as ordinary prose — a sentence
   * that asserts nothing while looking complete.
   */
  it('leaves an inline gap inside its sentence, byte for byte', () => {
    const draft = markdownToDraft(
      '# S\n\nThe station operates from [TODO: club.venue — where the station lives] on campus.',
      META,
    );
    expect(draft.sections[0]?.blocks[0]).toEqual({
      kind: 'p',
      text: 'The station operates from [TODO: club.venue — where the station lives] on campus.',
    });
  });

  /**
   * `farweb.org` is the Foundation for Amateur Radio's hijacked domain, now redirecting to a
   * gambling site while ARRL and QCWA pages still send applicants there. `redactBlockedLinks` is
   * the product's existing answer and this is its second call site.
   */
  it('withholds a blocklisted address instead of carrying it into the document', () => {
    const draft = markdownToDraft('# S\n\nApply at https://www.farweb.org/scholarships before May.', META);
    const text = (draft.sections[0]?.blocks[0] as { text: string }).text;
    expect(text).not.toMatch(/farweb/i);
    expect(text).toContain('link withheld');
    expect(text).toContain('before May');
  });
});

